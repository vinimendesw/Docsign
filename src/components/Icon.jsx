/**
 * Ícone padronizado do sistema.
 * @param {string} name        Nome do ícone (ver PATHS acima)
 * @param {number} size        Largura/altura em px (padrão: 20)
 * @param {string} color       Cor do stroke (padrão: currentColor)
 * @param {number} strokeWidth Espessura do traço (padrão: 2, padronizado em todo o app)
 */
export default function Icon({ name, size = 20, color = 'currentColor', strokeWidth = 2, className, style, ...rest }) {
  const shape = PATHS[name]

  if (!shape) {
    console.warn(`Icon: ícone "${name}" não existe no registry.`)
    return null
  }

  return (
    <svg
      viewBox="0 0 24 24"
      width={size}
      height={size}
      fill="none"
      stroke={color}
      strokeWidth={strokeWidth}
      strokeLinecap="round"
      strokeLinejoin="round"
      className={className}
      style={style}
      {...rest}
    >
      {shape}
    </svg>
  )
}
